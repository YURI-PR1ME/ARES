/************************************************************************************************** 
delay.c:延时程序,z=1，时为1ms
***************************************************************************************************/

#include "config.h"

/*****************************24MHZ z=1时精确延时1ms***********************************************/
void delay1ms(uint16 z)
{
	uch8 x,y;
	for(x=z; x>0; x--)
		for(y=235; y>0; y--);//235
}
/***************************************************************************************************/


/*---------------------------------------------------
 uS延时函数，含有输入参数 unsigned char t，无返回值
 unsigned char 是定义无符号字符变量，其值的范围是
 0~255 这里使用晶振12M，精确延时请使用汇编,大致延时
 长度如下 T=2xuS ,510us
----------------------------------------------------*/

void delay2us(uch8 x)
{
	while(--x);
}
