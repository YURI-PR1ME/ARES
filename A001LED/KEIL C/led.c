//加载头文件
#include "reg52.h"

//宏定义
#define uint8 unsigned int


//单片IO口配置
sbit led=P1^0;

//函数声明
void delay(uint8 a);



void main()
{
	while(1)
	{
		led=~led;//灯亮
		delay(150);

	}
}

void delay(uint8 a)
{
	uint8 b;
	while(a--)
	{
		for(b=120;b>0;b--);
	}
}
