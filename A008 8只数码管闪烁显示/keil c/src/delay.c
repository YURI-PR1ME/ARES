/************************************************************************************************** 
delay.c:延时程序,z=1，时为1ms
***************************************************************************************************/

#include "config.h"

/*****************************24MHZ z=1时精确延时1ms***********************************************/
void delay1ms(uint16 z)
{
	uint16 x,y;
	for(x=z; x>0; x--)
		for(y=245; y>0; y--);
}
/***************************************************************************************************/




/************************24M晶振，1ms的延时成***************************************/
void delay1ms24m(uint16 x)
{
	uint16 z;
    uint16 y;
    for(z=x;z>0;z--)
		for(y=246;y>0;y--);

}



