/************************************************************************************************** 
delay.c:延时程序,z=1，时为1ms
***************************************************************************************************/

#include "config.h"

/*****************************24MHZ z=1时精确延时1ms***********************************************/
void delay1ms(uint16 z)
{
	uch8 x,y;
	for(x=z; x>0; x--)
		for(y=235; y>0; y--);
}
